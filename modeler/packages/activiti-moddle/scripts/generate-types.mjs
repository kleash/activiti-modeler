#!/usr/bin/env node
/**
 * Generates src/generated/types.ts from the activiti moddle descriptor, so the TypeScript types cannot drift from it.
 *
 *   node scripts/generate-types.mjs            write the file
 *   node scripts/generate-types.mjs --check    fail when the file is stale
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DESCRIPTOR = resolve(HERE, '../src/descriptors/activiti.json');
const OUTPUT = resolve(HERE, '../src/generated/types.ts');

const descriptor = JSON.parse(readFileSync(DESCRIPTOR, 'utf8'));
const typeNames = new Set(descriptor.types.map((t) => t.name));

function tsType(property) {
  if (property.isMany) return `${elementType(property.type)}[]`;
  return elementType(property.type);
}

function elementType(type) {
  switch (type) {
    case 'String':
      return 'string';
    case 'Boolean':
      return 'boolean';
    case 'Integer':
    case 'Real':
      return 'number';
    default:
      break;
  }
  const local = type.startsWith('activiti:') ? type.slice('activiti:'.length) : type;
  if (typeNames.has(local)) return `Activiti${local}`;
  return 'ModdleElement';
}

/** Property key as used with get() / updateProperties(): `activiti:x`, or the plain name for redefined bpmn: properties. */
function key(property) {
  return property.name.startsWith('bpmn:') ? property.name.slice('bpmn:'.length) : `activiti:${property.name}`;
}

const mixins = descriptor.types.filter((t) => t.extends);
const elements = descriptor.types.filter((t) => !t.extends);

const lines = [];
lines.push('// GENERATED by scripts/generate-types.mjs from src/descriptors/activiti.json. Do not edit.');
lines.push("import type { ModdleElement } from 'bpmn-moddle';");
lines.push('');
lines.push('export type { ModdleElement };');
lines.push('');
lines.push('// --- attributes and properties that the activiti: namespace adds to bpmn: types ---------------------------------');
lines.push('');
for (const type of mixins) {
  lines.push(`/** Added to ${type.extends.join(', ')}. */`);
  lines.push(`export interface Activiti${type.name}Attributes {`);
  for (const p of type.properties) lines.push(`  '${key(p)}'?: ${tsType(p)};`);
  lines.push('}');
  lines.push('');
}
lines.push('/** Mixin interface name by the bpmn: type it extends (a type can be listed under several parents). */');
lines.push('export interface ActivitiAttributesByBpmnType {');
const byBpmn = new Map();
for (const type of mixins) for (const parent of type.extends) byBpmn.set(parent, [...(byBpmn.get(parent) ?? []), `Activiti${type.name}Attributes`]);
for (const [parent, names] of [...byBpmn].sort()) lines.push(`  '${parent}': ${names.join(' & ')};`);
lines.push('}');
lines.push('');
lines.push('// --- extension elements (children of bpmn:ExtensionElements and of activiti: elements) ---------------------------');
lines.push('');
for (const type of elements) {
  lines.push(`export interface Activiti${type.name} extends ModdleElement {`);
  lines.push(`  $type: 'activiti:${type.name}';`);
  for (const p of type.properties) lines.push(`  ${p.name}?: ${tsType(p)};`);
  lines.push('}');
  lines.push('');
}
lines.push('export interface ActivitiExtensionElementsByType {');
for (const type of elements) lines.push(`  'activiti:${type.name}': Activiti${type.name};`);
lines.push('}');
lines.push('');
lines.push('export type ActivitiExtensionType = keyof ActivitiExtensionElementsByType;');
lines.push('');

const content = `${lines.join('\n')}`;
if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== content) {
    console.error('src/generated/types.ts is stale; run node scripts/generate-types.mjs');
    process.exit(1);
  }
  console.log('generated types up to date');
} else {
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, content);
  console.log(`wrote ${OUTPUT}`);
}
